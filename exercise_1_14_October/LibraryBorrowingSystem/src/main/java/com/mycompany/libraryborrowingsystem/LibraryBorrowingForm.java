    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // 1. Retrieve member details
        String name = txtMemberName.getText().trim();
        String membershipNo = txtMembershipNumber.getText().trim();
        String contactNo = txtContactNumber.getText().trim();
        String address = txtAddress.getText().trim();

        // 2. Retrieve the selected book category
        String category = "";
        if (lstBookCategory.getSelectedValue() != null) {
            category = lstBookCategory.getSelectedValue().toString();
        }

        // 3. Determine the borrowing period
        String period = "";
        if (rdo7Days.isSelected()) {
            period = "7 Days";
        } else if (rdo14Days.isSelected()) {
            period = "14 Days";
        } else if (rdo21Days.isSelected()) {
            period = "21 Days";
        }

        // 4. Validation
        if (name.isEmpty() || membershipNo.isEmpty() || contactNo.isEmpty()|| address.isEmpty() || category.isEmpty() || period.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Please complete all required information:\n"
                + "member details, book category and borrowing period.",
                "Missing Information", JOptionPane.ERROR_MESSAGE);
        return;
        }

        // 5. Check the additional options
        String email = chkEmailNotification.isSelected() ? "Yes" : "No";
        String collection = chkBookCollection.isSelected() ? "Yes" : "No";

        // 6. Display everything
        String summary = "BORROWING DETAILS\n\n"
            + "Member Name: " + name + "\n"
            + "Membership Number: " + membershipNo + "\n"
            + "Contact Number: " + contactNo + "\n"
            + "Residential Address: " + address + "\n"
            + "Book Category: " + category + "\n"
            + "Borrowing Period: " + period + "\n"
            + "Email Notification: " + email + "\n"
            + "Book Collection Required: " + collection;

        JOptionPane.showMessageDialog(this, summary,
            "Borrowing Submitted", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnSubmitActionPerformed

